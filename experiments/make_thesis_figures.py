"""
Regenerate every thesis figure (Phase 8, T8.1) and write the figure manifest.

    python experiments\\make_thesis_figures.py                 # all figures, 4 in parallel
    python experiments\\make_thesis_figures.py --only fig01 fig03
    python experiments\\make_thesis_figures.py --list

Each experiments/thesis/figNN_<slug>.py runs in its own Python process (clean
matplotlib state; one failing figure does not stop the others). Afterwards the
sidecars in results/phase8/figures/ are collected into

* figures/thesis/MANIFEST.md (tracked in git): for every figure the caption,
  the command that regenerates it, the parameters, the input files with the
  commits that produced them, the checks and the notes. It contains no
  timestamps, so it changes only when a figure's data, checks or notes change.
* results/phase8/figure_checks.json: the full records, including run times
  and the code commit.

Exit code 0 only if every figure ran and every check passed.
"""

import argparse
import json
import os
import subprocess
import sys
import time
from collections import OrderedDict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from config import CFG, FIGURES_DIR, RESULTS_DIR  # noqa: E402

THESIS_DIR = ROOT / "experiments" / "thesis"


def discover() -> list:
    return sorted(p for p in THESIS_DIR.glob("fig[0-9][0-9]_*.py"))


def run_one(path: Path) -> dict:
    env = dict(os.environ, MPLBACKEND="Agg", PYTHONIOENCODING="utf-8")
    t0 = time.perf_counter()
    proc = subprocess.run([sys.executable, str(path), "--quiet"], cwd=ROOT, env=env,
                          capture_output=True, text=True, encoding="utf-8", errors="replace")
    return {"name": path.stem, "returncode": proc.returncode, "stdout": proc.stdout,
            "stderr": proc.stderr, "seconds": time.perf_counter() - t0}


def load_sidecars(names: list, folder: Path) -> "OrderedDict[str, dict]":
    out = OrderedDict()
    for name in names:
        path = folder / f"{name}.json"
        if path.exists():
            out[name] = json.loads(path.read_text(encoding="utf-8"))
    return out


def _group_inputs(inputs: list) -> list:
    """Collapse inputs into one line per (folder, commit), e.g. 'phase1: 12 files, commit 6051c9d'."""
    groups = OrderedDict()
    for item in inputs:
        folder = item["file"].split("/")[0]
        key = (folder, item.get("commit") or "-")
        groups.setdefault(key, []).append(item["file"].split("/", 1)[-1])
    lines = []
    for (folder, commit), files in groups.items():
        shown = ", ".join(files) if len(files) <= 4 else f"{files[0]} ... {files[-1]}"
        commit_txt = f"commit {commit}" if commit != "-" else "no commit recorded"
        lines.append(f"{folder}: {len(files)} file{'s' if len(files) > 1 else ''} ({shown}), {commit_txt}")
    return lines


def write_manifest(records: "OrderedDict[str, dict]", missing: list, path: Path) -> None:
    """Deterministic Markdown manifest of all thesis figures."""
    lines = ["# Thesis figures", "",
             "Generated by `python experiments\\make_thesis_figures.py`; do not edit by hand.",
             "Each figure is regenerated by the command given in its section.", "",
             "| Figure | Chapter | Phases | Checks | Notes |", "| --- | --- | --- | --- | --- |"]
    for name, r in records.items():
        status = f"{r['n_passed']} passed" + (f", **{r['n_failed']} failed**" if r["n_failed"] else "")
        lines.append(f"| {name} | {r['chapter']} | {', '.join(map(str, r['phases']))} | "
                     f"{status} | {len(r['notes'])} |")
    for name in missing:
        lines.append(f"| {name} | (not run) | | | |")
    for name, r in records.items():
        lines += ["", f"## {name}: {r['title']}", "", r["caption"], "",
                  f"Command: `{r['command']}`", ""]
        if r["params"]:
            lines.append("Parameters: " + "; ".join(f"{k} = {v}" for k, v in r["params"].items()))
            lines.append("")
        lines.append("Inputs:")
        lines += [f"- {s}" for s in _group_inputs(r["inputs"])] or ["- none"]
        lines += ["", "Checks:"]
        lines += [f"- {c['line']}" for c in r["checks"]]
        if r["notes"]:
            lines += ["", "Notes:"]
            lines += [f"- {n}" for n in r["notes"]]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--only", nargs="+", default=None, help="figure keys or names, e.g. fig01 fig03")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--list", action="store_true", help="list the figure scripts and exit")
    args = ap.parse_args(argv)

    scripts = discover()
    if args.list:
        for p in scripts:
            print(p.relative_to(ROOT))
        return 0
    todo = scripts if not args.only else \
        [p for p in scripts if any(p.stem == k or p.stem.startswith(k + "_") for k in args.only)]
    if not todo:
        print("no figure scripts selected")
        return 1

    sidecars = RESULTS_DIR / CFG.thesis.results_subdir / "figures"
    for p in todo:                       # a figure that fails to run must not keep an old record
        (sidecars / f"{p.stem}.json").unlink(missing_ok=True)

    t0 = time.perf_counter()
    with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        runs = list(pool.map(run_one, todo))
    errors = 0
    for r in runs:
        summary = (r["stdout"].strip().splitlines() or ["(no output)"])[-1]
        if r["returncode"] != 0 and not summary.startswith(r["name"]):
            errors += 1
            tail = "\n    ".join(r["stderr"].strip().splitlines()[-6:])
            print(f"{r['name']}: ERROR (exit {r['returncode']}, {r['seconds']:.1f} s)\n    {tail}")
        else:
            print(summary)

    names = [p.stem for p in scripts]
    records = load_sidecars(names, sidecars)
    missing = [n for n in names if n not in records]
    manifest = FIGURES_DIR / CFG.thesis.figure_subdir / "MANIFEST.md"
    write_manifest(records, missing, manifest)
    checks_path = RESULTS_DIR / CFG.thesis.results_subdir / "figure_checks.json"
    checks_path.parent.mkdir(parents=True, exist_ok=True)
    checks_path.write_text(json.dumps(list(records.values()), indent=2), encoding="utf-8")

    ran = {r["name"] for r in runs}
    n_pass = sum(records[n]["n_passed"] for n in ran if n in records)
    n_fail = sum(records[n]["n_failed"] for n in ran if n in records)
    print(f"\n{len(todo)} figures run in {time.perf_counter() - t0:.1f} s: {n_pass} checks passed, "
          f"{n_fail} failed, {errors} scripts with errors")
    print(f"manifest: {manifest.relative_to(ROOT)} ({len(records)} of {len(names)} figures documented)")
    return 0 if (n_fail == 0 and errors == 0) else 1


if __name__ == "__main__":
    raise SystemExit(main())
