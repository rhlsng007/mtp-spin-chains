"""
Exact diagonalization (Phase 1, task T1.2).

Why symmetry sectors?
---------------------
In the ordered phase of a finite open TFIM the two lowest states are the
even and odd cat states (|up...up> +/- |down...down>)/sqrt(2). Their splitting
falls exponentially with N (it is the Majorana edge-mode splitting of the
dual Kitaev chain) and drops below machine precision for N = 14 at small h.
A plain eigsh call would then return an arbitrary mixture of the two, and
the entanglement entropy would jump between ln 2 and 0 from one field value
to the next.

We avoid this by diagonalizing every Z2 spin-flip sector separately. A sector
with characters s_g = +/-1 has the orthonormal basis

    |r, s> = |G|^(-1/2) sum_{g in G} chi_s(g) |r XOR g>

with one representative r per orbit. Every flip mask changes every index,
so all orbits have exactly |G| elements and every sector has dimension
2^N / |G|. Inside a sector the spectrum has no symmetry-enforced
near-degeneracy, so eigsh is well conditioned, and each returned state has a
definite parity, which is exactly what the parity-conserving HVA prepares in
Phase 2.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass
from functools import lru_cache

import numpy as np
import scipy.sparse as sp
from scipy.sparse.linalg import eigsh

from config import CFG
from models.hamiltonians import basis_indices, build_hamiltonian, symmetry_generators


# ---------------------------------------------------------------------------
# Symmetry sectors
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class Sector:
    labels: tuple            # character (+1 / -1) of each generator
    isometry: sp.csr_matrix  # V: full space <- sector, shape (2^N, 2^N / |G|)

    @property
    def dim(self) -> int:
        return self.isometry.shape[1]


def _group_elements(generators: tuple) -> list:
    """All products of the generators as (mask, subset), with subset a 0/1 tuple."""
    elements = []
    for subset in itertools.product((0, 1), repeat=len(generators)):
        mask = 0
        for use, g in zip(subset, generators):
            if use:
                mask ^= g
        elements.append((mask, subset))
    masks = [m for m, _ in elements]
    if len(set(masks)) != len(masks):
        raise ValueError("symmetry generators are not independent")
    return elements


@lru_cache(maxsize=64)
def symmetry_sectors(n_sites: int, generators: tuple) -> tuple:
    """
    All sectors of the group generated by the given flip masks.

    The all-plus sector (fully symmetric) comes first. Cached, because the
    same sectors are reused at every point of a parameter sweep.
    """
    dim = 2 ** n_sites
    if not generators:
        return (Sector(labels=(), isometry=sp.identity(dim, format="csr")),)

    idx = basis_indices(n_sites)
    elements = _group_elements(generators)
    orbit_min = np.min(np.stack([idx ^ m for m, _ in elements]), axis=0)
    reps = idx[idx == orbit_min]
    n_reps = len(reps)
    norm = 1.0 / np.sqrt(len(elements))

    sectors = []
    for labels in itertools.product((1, -1), repeat=len(generators)):
        rows, vals = [], []
        for mask, subset in elements:
            chi = np.prod([s for s, use in zip(labels, subset) if use]) if any(subset) else 1
            rows.append(reps ^ mask)
            vals.append(np.full(n_reps, chi * norm))
        cols = np.tile(np.arange(n_reps), len(elements))
        V = sp.csr_matrix((np.concatenate(vals), (np.concatenate(rows), cols)),
                          shape=(dim, n_reps))
        sectors.append(Sector(labels=tuple(int(s) for s in labels), isometry=V))
    return tuple(sectors)


# ---------------------------------------------------------------------------
# Eigensolver
# ---------------------------------------------------------------------------
def _fix_sign(vecs: np.ndarray) -> np.ndarray:
    """Make the largest-magnitude entry of each column real and positive."""
    for j in range(vecs.shape[1]):
        k = np.argmax(np.abs(vecs[:, j]))
        vecs[:, j] *= np.conj(vecs[k, j]) / abs(vecs[k, j])
    return vecs


def lowest_eigenpairs(H, k: int, dense_max_dim: int = None, tol: float = None,
                      seed: int = None, method: str = "auto") -> tuple:
    """
    Lowest k eigenvalues (ascending) and eigenvectors (columns) of Hermitian H.

    method = "auto" uses dense eigh for dimensions up to dense_max_dim and
    scipy's Lanczos eigsh above; "dense" and "sparse" force one of them.
    eigsh starts from a fixed random vector, so results are reproducible and
    the start vector has overlap with every symmetry sector.
    """
    ed = CFG.ed
    dense_max_dim = ed.dense_max_dim if dense_max_dim is None else dense_max_dim
    tol = ed.eigsh_tol if tol is None else tol
    seed = ed.eigsh_seed if seed is None else seed

    dim = H.shape[0]
    k = min(k, dim)
    use_dense = method == "dense" or (method == "auto" and dim <= dense_max_dim) or k >= dim - 1
    if use_dense:
        dense = H.toarray() if sp.issparse(H) else np.asarray(H)
        w, v = np.linalg.eigh(dense)
        w, v = w[:k], v[:, :k]
    else:
        v0 = np.random.default_rng(seed).standard_normal(dim)
        w, v = eigsh(H, k=k, which="SA", tol=tol, v0=v0)
        order = np.argsort(w)
        w, v = w[order], v[:, order]
    return w, _fix_sign(np.array(v))


# ---------------------------------------------------------------------------
# Results
# ---------------------------------------------------------------------------
@dataclass
class ExactResult:
    """
    Lowest levels of H resolved by symmetry sector.

    sector_energies[s, n] : n-th level in sector s (ascending)
    sector_states[s]      : lowest state of sector s, embedded in the full space
    energies              : lowest levels of the full spectrum (all sectors merged)
    ground_sector         : sector holding the reference ground state
    """
    n_sites: int
    sector_labels: list
    sector_energies: np.ndarray
    sector_states: np.ndarray
    energies: np.ndarray
    ground_sector: int

    @property
    def ground_state(self) -> np.ndarray:
        return self.sector_states[self.ground_sector]

    @property
    def ground_energy(self) -> float:
        return float(self.sector_energies[self.ground_sector, 0])

    @property
    def gap(self) -> float:
        """E1 - E0 over the full spectrum (exponentially small in an ordered phase)."""
        return float(self.energies[1] - self.energies[0])

    @property
    def gap_sector(self) -> float:
        """E1 - E0 inside the ground-state sector: the physical excitation gap."""
        return float(self.sector_energies[self.ground_sector, 1]
                     - self.sector_energies[self.ground_sector, 0])

    @property
    def ground_labels(self) -> tuple:
        return self.sector_labels[self.ground_sector]


def solve(H, n_sites: int, generators: tuple = (), k_per_sector: int = None,
          degeneracy_tol: float = None, method: str = "auto") -> ExactResult:
    """
    Diagonalize H in every symmetry sector generated by the flip masks.

    Reference ground state: the lowest state over all sectors. If several
    sectors are degenerate to within degeneracy_tol (e.g. the cluster SPT
    phase with open boundaries), the first one in the order of
    symmetry_sectors (fully symmetric first) is taken, so the choice is
    deterministic.
    """
    ed = CFG.ed
    k = ed.k_per_sector if k_per_sector is None else k_per_sector
    tol = ed.degeneracy_tol if degeneracy_tol is None else degeneracy_tol

    sectors = symmetry_sectors(n_sites, tuple(generators))
    k = min(k, sectors[0].dim)
    energies = np.full((len(sectors), k), np.nan)
    states = np.zeros((len(sectors), 2 ** n_sites), dtype=H.dtype)

    for s, sector in enumerate(sectors):
        V = sector.isometry
        H_sector = (V.T @ H @ V).tocsr()
        w, v = lowest_eigenpairs(H_sector, k, method=method)
        energies[s, :len(w)] = w
        psi = V @ v[:, 0]
        states[s] = _fix_sign((psi / np.linalg.norm(psi))[:, None])[:, 0]

    lowest = energies[:, 0]
    ground_sector = int(np.flatnonzero(lowest <= lowest.min() + tol)[0])
    merged = np.sort(energies[np.isfinite(energies)])

    return ExactResult(
        n_sites=n_sites,
        sector_labels=[sec.labels for sec in sectors],
        sector_energies=energies,
        sector_states=states,
        energies=merged,
        ground_sector=ground_sector,
    )


def solve_model(model: str, n_sites: int, use_symmetry: bool = True,
                method: str = "auto", **params) -> ExactResult:
    """
    Build and diagonalize a model, e.g. solve_model('tfim', 10, J=1, h=1).

    `params` are passed to the Hamiltonian; `boundary` defaults to "open".
    """
    boundary = params.get("boundary", "open")
    H = build_hamiltonian(model, n_sites, **params)
    generators = symmetry_generators(model, n_sites, boundary) if use_symmetry else ()
    return solve(H, n_sites, generators, method=method)


def dense_spectrum(H) -> np.ndarray:
    """Full spectrum by dense diagonalization (validation only, small N)."""
    dense = H.toarray() if sp.issparse(H) else np.asarray(H)
    return np.linalg.eigvalsh(dense)
